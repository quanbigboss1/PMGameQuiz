-- =========================================================
-- 2. USERS
-- =========================================================

CREATE TABLE users (
    userid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    passwordhash VARCHAR(255) NOT NULL,

    fullname VARCHAR(100),
    avatarurl VARCHAR(500),
    dateofbirth DATE,
    gender VARCHAR(20),
    country VARCHAR(100),
    bio VARCHAR(500),

    xp INTEGER NOT NULL DEFAULT 0,
    level INTEGER NOT NULL DEFAULT 1,
    coins INTEGER NOT NULL DEFAULT 0,

    hearts INTEGER NOT NULL DEFAULT 5,
    maxhearts INTEGER NOT NULL DEFAULT 5,

    ispremium BOOLEAN NOT NULL DEFAULT FALSE,
    isactive BOOLEAN NOT NULL DEFAULT TRUE,

    role VARCHAR(20) NOT NULL DEFAULT 'User',

    createdat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    lastloginat TIMESTAMPTZ
);


-- =========================================================
-- 3. SUBSCRIPTIONS
-- =========================================================

CREATE TABLE subscriptions (
    subscriptionid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    userid INTEGER NOT NULL,

    planname VARCHAR(100) NOT NULL,
    price NUMERIC(12,2) NOT NULL DEFAULT 0,

    startdate TIMESTAMPTZ NOT NULL,
    enddate TIMESTAMPTZ,

    status VARCHAR(30) NOT NULL DEFAULT 'Active',
    paymentmethod VARCHAR(50),
    transactioncode VARCHAR(100),

    createdat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_subscriptions_users
        FOREIGN KEY (userid)
        REFERENCES users(userid)
        ON DELETE CASCADE
);


-- =========================================================
-- 4. LANGUAGES
-- =========================================================

CREATE TABLE languages (
    languageid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    languagecode VARCHAR(10) NOT NULL UNIQUE,
    languagename VARCHAR(100) NOT NULL,
    nativename VARCHAR(100),

    flagurl VARCHAR(500),

    isactive BOOLEAN NOT NULL DEFAULT TRUE,

    createdat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 5. USER LANGUAGES
-- =========================================================

CREATE TABLE userlanguages (
    userlanguageid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    userid INTEGER NOT NULL,
    languageid INTEGER NOT NULL,

    currentlevel INTEGER NOT NULL DEFAULT 1,
    xp INTEGER NOT NULL DEFAULT 0,

    islearning BOOLEAN NOT NULL DEFAULT TRUE,

    startedat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_userlanguages_users
        FOREIGN KEY (userid)
        REFERENCES users(userid)
        ON DELETE CASCADE,

    CONSTRAINT fk_userlanguages_languages
        FOREIGN KEY (languageid)
        REFERENCES languages(languageid),

    CONSTRAINT uq_userlanguages
        UNIQUE(userid, languageid)
);


-- =========================================================
-- 6. COURSES
-- =========================================================

CREATE TABLE courses (
    courseid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    languageid INTEGER NOT NULL,

    coursename VARCHAR(200) NOT NULL,
    description TEXT,

    imageurl VARCHAR(500),
    difficulty VARCHAR(50),

    totalxp INTEGER NOT NULL DEFAULT 0,

    ispublished BOOLEAN NOT NULL DEFAULT FALSE,

    createdat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_courses_languages
        FOREIGN KEY (languageid)
        REFERENCES languages(languageid)
);


-- =========================================================
-- 7. LESSONS
-- =========================================================

CREATE TABLE lessons (
    lessonid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    courseid INTEGER NOT NULL,

    lessonname VARCHAR(200) NOT NULL,
    description TEXT,

    lessonorder INTEGER NOT NULL DEFAULT 1,

    difficulty VARCHAR(50),

    xpreward INTEGER NOT NULL DEFAULT 20,

    estimatedminutes INTEGER NOT NULL DEFAULT 10,

    ispublished BOOLEAN NOT NULL DEFAULT TRUE,

    createdat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_lessons_courses
        FOREIGN KEY (courseid)
        REFERENCES courses(courseid)
        ON DELETE CASCADE
);


-- =========================================================
-- 8. USER LESSON PROGRESS
-- =========================================================

CREATE TABLE userlessonprogress (
    progressid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    userid INTEGER NOT NULL,
    lessonid INTEGER NOT NULL,

    progresspercent INTEGER NOT NULL DEFAULT 0,

    iscompleted BOOLEAN NOT NULL DEFAULT FALSE,

    score INTEGER NOT NULL DEFAULT 0,
    xpreceived INTEGER NOT NULL DEFAULT 0,

    startedat TIMESTAMPTZ,
    completedat TIMESTAMPTZ,

    lastaccessedat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

