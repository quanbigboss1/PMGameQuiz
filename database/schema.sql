SELECT * FROM users;

SELECT * FROM languages;

SELECT
    c.courseid,
    c.coursename,
    l.languagename,
    c.difficulty,
    c.totalxp
FROM courses c
INNER JOIN languages l
    ON c.languageid = l.languageid;

SELECT
    le.lessonid,
    le.lessonname,
    c.coursename,
    le.lessonorder,
    le.xpreward
FROM lessons le
INNER JOIN courses c
    ON le.courseid = c.courseid
ORDER BY c.courseid, le.lessonorder;

SELECT
    v.vocabularyid,
    l.languagename,
    v.word,
    v.pronunciation,
    v.meaning
FROM vocabulary v
INNER JOIN languages l
    ON v.languageid = l.languageid;

SELECT
    u.username,
    le.lessonname,
    p.progresspercent,
    p.iscompleted,
    p.score,
    p.xpreceived
FROM userlessonprogress p
INNER JOIN users u
    ON p.userid = u.userid
INNER JOIN lessons le
    ON p.lessonid = le.lessonid
ORDER BY u.userid, le.lessonorder;

SELECT
    lb.rankposition,
    u.username,
    u.fullname,
    lb.xp,
    lb.periodtype
FROM leaderboard lb
INNER JOIN users u
    ON lb.userid = u.userid
WHERE lb.periodtype = 'Weekly'
ORDER BY lb.rankposition;

SELECT
    u.username,
    a.achievementname,
    ua.progressvalue,
    a.requirementvalue,
    ua.iscompleted,
    ua.unlockedat
FROM userachievements ua
INNER JOIN users u
    ON ua.userid = u.userid
INNER JOIN achievements a
    ON ua.achievementid = a.achievementid
WHERE u.userid = 1;

SELECT
    u.username,
    g.gamename,
    gs.score,
    gs.correctanswers,
    gs.wronganswers,
    gs.xpreceived,
    gs.coinsreceived,
    gs.durationseconds
FROM gamesessions gs
INNER JOIN users u
    ON gs.userid = u.userid
INNER JOIN games g
    ON gs.gameid = g.gameid
ORDER BY gs.startedat DESC;

SELECT
    q.quizname,
    qq.questionid,
    qq.questiontext,
    qa.answertext,
    qa.iscorrect
FROM quizzes q
INNER JOIN quizquestions qq
    ON q.quizid = qq.quizid
INNER JOIN quizanswers qa
    ON qq.questionid = qa.questionid
ORDER BY q.quizid, qq.questionid, qa.answerorder;